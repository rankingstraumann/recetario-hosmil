-- ---------------- Scoring (solo columnas de scoring; NO status) ----------------
CREATE FUNCTION public.score_digital_lead()
RETURNS trigger
LANGUAGE plpgsql SET search_path TO 'pg_catalog'
AS $f$
DECLARE s integer := 0;
BEGIN
  IF NEW.uses_intraoral_scanner IS TRUE THEN
    s := s + 10;
    IF coalesce(btrim(NEW.current_scanner), '') <> '' THEN s := s + 5; END IF;
  ELSIF NEW.uses_intraoral_scanner IS FALSE THEN
    s := s + 5;
  END IF;

  s := s + CASE NEW.need
    WHEN 'trade_up' THEN 25 WHEN 'renew' THEN 25 WHEN 'first_scanner' THEN 20
    WHEN 'digital_flow' THEN 15 WHEN 'know_sirios' THEN 10 ELSE 0 END;

  s := s + CASE NEW.purchase_timeline
    WHEN 'now' THEN 25 WHEN '1_3_months' THEN 20 WHEN '3_6_months' THEN 10 ELSE 0 END;

  IF NEW.wants_demo IS TRUE AND NEW.wants_quote IS TRUE THEN s := s + 30;
  ELSIF NEW.wants_quote IS TRUE THEN s := s + 25;
  ELSIF NEW.wants_demo IS TRUE THEN s := s + 20;
  END IF;

  IF NEW.high_intent_override IS TRUE THEN s := greatest(s, 70); END IF;

  NEW.score := least(s, 100);
  IF NEW.score >= 70 THEN
    NEW.temperature := 'hot';
    IF NEW.status IN ('new','qualifying','cold','warm','hot') THEN NEW.status := 'hot'; END IF;
  ELSIF NEW.score >= 40 THEN
    NEW.temperature := 'warm';
    IF NEW.status IN ('new','qualifying','cold','warm','hot') THEN NEW.status := 'warm'; END IF;
  ELSE
    NEW.temperature := 'cold';
    IF NEW.status IN ('new','qualifying','cold','warm','hot') THEN NEW.status := 'cold'; END IF;
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END $f$;

CREATE TRIGGER trg_score_digital_lead
BEFORE INSERT OR UPDATE OF uses_intraoral_scanner, current_scanner, need, purchase_timeline,
  wants_demo, wants_quote, high_intent_override
ON public.digital_leads FOR EACH ROW EXECUTE FUNCTION public.score_digital_lead();

CREATE FUNCTION public.touch_digital_lead()
RETURNS trigger LANGUAGE plpgsql SET search_path TO 'pg_catalog'
AS $f$ BEGIN NEW.updated_at := now(); RETURN NEW; END $f$;

CREATE TRIGGER trg_touch_digital_lead
BEFORE UPDATE ON public.digital_leads FOR EACH ROW EXECUTE FUNCTION public.touch_digital_lead();

-- ---------------- RPC ----------------
CREATE FUNCTION public.assign_digital_lead(
  p_lead_id uuid, p_assigned_to_name text, p_assigned_to_email text DEFAULT NULL)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog'
AS $f$
DECLARE v_name text := btrim(coalesce(p_assigned_to_name,'')); v_email text := nullif(btrim(coalesce(p_assigned_to_email,'')),'');
        v_lead public.digital_leads%ROWTYPE;
BEGIN
  IF NOT public.is_lead_admin() THEN RAISE EXCEPTION 'No autorizado' USING ERRCODE='42501'; END IF;
  IF v_name = '' OR length(v_name) > 120 THEN RAISE EXCEPTION 'Nombre de asignado invalido' USING ERRCODE='22023'; END IF;
  SELECT * INTO v_lead FROM public.digital_leads WHERE id = p_lead_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Lead no existe' USING ERRCODE='P0002'; END IF;
  IF v_email IS NULL THEN
    SELECT a.email INTO v_email FROM public.digital_lead_assignees a
    WHERE lower(btrim(a.nombre)) = lower(v_name) AND a.activo;
  END IF;
  UPDATE public.digital_leads SET
    assigned_to_name = v_name, assigned_to_email = v_email,
    assigned_at = now(), assigned_by = auth.uid(),
    status = CASE WHEN v_lead.status IN ('new','qualifying','cold','warm','hot','assigned') THEN 'assigned' ELSE v_lead.status END
  WHERE id = p_lead_id;
  INSERT INTO public.digital_lead_activities(lead_id, actor_user_id, event_type, detail)
  VALUES (p_lead_id, auth.uid(), 'assigned',
    jsonb_build_object('assigned_to_name', v_name, 'assigned_to_email', v_email,
                       'previous_assignee', v_lead.assigned_to_name));
END $f$;

CREATE FUNCTION public.update_digital_lead_notes(p_lead_id uuid, p_notes text)
RETURNS void
LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'pg_catalog'
AS $f$
BEGIN
  IF NOT public.is_lead_admin() THEN RAISE EXCEPTION 'No autorizado' USING ERRCODE='42501'; END IF;
  IF length(coalesce(p_notes,'')) > 4000 THEN RAISE EXCEPTION 'Nota demasiado larga' USING ERRCODE='22023'; END IF;
  UPDATE public.digital_leads SET daniel_notes = nullif(btrim(coalesce(p_notes,'')),'') WHERE id = p_lead_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'Lead no existe' USING ERRCODE='P0002'; END IF;
  INSERT INTO public.digital_lead_activities(lead_id, actor_user_id, event_type, detail)
  VALUES (p_lead_id, auth.uid(), 'note_updated', jsonb_build_object('length', length(coalesce(p_notes,''))));
END $f$;

