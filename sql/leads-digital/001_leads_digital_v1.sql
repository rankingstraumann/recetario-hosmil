CREATE TABLE IF NOT EXISTS public.lead_admin_users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE FUNCTION public.is_lead_admin()
RETURNS boolean
LANGUAGE sql STABLE SECURITY DEFINER SET search_path TO 'pg_catalog'
AS $f$
  SELECT EXISTS (SELECT 1 FROM public.lead_admin_users WHERE user_id = auth.uid());
$f$;

CREATE TABLE IF NOT EXISTS public.digital_lead_assignees (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  nombre text NOT NULL CHECK (length(btrim(nombre)) > 0),
  email text,
  activo boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS uq_digital_lead_assignees_nombre
  ON public.digital_lead_assignees (lower(btrim(nombre)));

CREATE TABLE IF NOT EXISTS public.digital_leads (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  source_channel text NOT NULL DEFAULT 'meta_whatsapp',
  campaign_name text,
  phone_e164 text,
  contact_name text,
  clinic_name text,
  commune text,
  uses_intraoral_scanner boolean,
  current_scanner text,
  need text CHECK (need IS NULL OR need IN
    ('renew','trade_up','first_scanner','digital_flow','know_sirios','information_only','other')),
  purchase_timeline text CHECK (purchase_timeline IS NULL OR purchase_timeline IN
    ('now','1_3_months','3_6_months','later','evaluating')),
  wants_demo boolean,
  wants_quote boolean,
  high_intent_override boolean NOT NULL DEFAULT false,
  high_intent_reason text,
  score smallint NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
  temperature text NOT NULL DEFAULT 'cold' CHECK (temperature IN ('cold','warm','hot')),
  status text NOT NULL DEFAULT 'new' CHECK (status IN
    ('new','qualifying','cold','warm','hot','assigned','contacted','demo','quote','won','lost')),
  ai_summary text,
  daniel_notes text,
  assigned_to_name text,
  assigned_to_email text,
  assigned_at timestamptz,
  assigned_by uuid,
  is_test boolean NOT NULL DEFAULT false
);
CREATE INDEX IF NOT EXISTS idx_digital_leads_created_at  ON public.digital_leads (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_digital_leads_temperature ON public.digital_leads (temperature, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_digital_leads_status      ON public.digital_leads (status, created_at DESC);

CREATE TABLE IF NOT EXISTS public.digital_lead_activities (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id uuid NOT NULL REFERENCES public.digital_leads(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  actor_user_id uuid,
  event_type text NOT NULL,
  detail jsonb NOT NULL DEFAULT '{}'::jsonb
);
CREATE INDEX IF NOT EXISTS idx_digital_lead_activities_lead ON public.digital_lead_activities (lead_id, created_at DESC);

-- Preparada, SIN uso en esta fase.
CREATE TABLE IF NOT EXISTS public.digital_lead_messages (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lead_id uuid NOT NULL REFERENCES public.digital_leads(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  direction text NOT NULL CHECK (direction IN ('inbound','outbound')),
  channel text NOT NULL DEFAULT 'whatsapp',
  message_text text,
  provider_message_id text,
  metadata jsonb NOT NULL DEFAULT '{}'::jsonb
